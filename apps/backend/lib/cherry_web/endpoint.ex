defmodule CherryWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :cherry

  # First, like Phoenix's own `force_ssl`, but switchable at runtime (FORCE_SSL).
  plug(CherryWeb.Plugs.ForceSSL)

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_cherry_key",
    signing_salt: "ZJS2H4Vh",
    same_site: "Lax"
  ]

  socket("/socket", CherryWeb.UserSocket,
    websocket: [check_origin: false],
    longpoll: false
  )

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug(Plug.Static,
    at: "/",
    from: :cherry,
    gzip: not code_reloading?,
    only: CherryWeb.static_paths(),
    raise_on_missing_only: code_reloading?
  )

  # Profile photos of the local storage adapter (Cherry.Storage.Local), stored as
  # UPLOADS_DIR/<storage_key>. The directory is resolved per request (runtime
  # config). Only published photos are exposed: `photos/` (random keys) and the
  # legacy `profiles/`; never the `pending/` upload area nor `.tmp/`.
  # Directories are never listed. Deleted photos are removed from disk, so the
  # cache lifetime is one day (not "immutable"): caches forget them soon.
  plug(CherryWeb.Plugs.LocalUploads,
    at: "/uploads",
    from: {Cherry.Storage.Local, :uploads_dir, []},
    only: ~w(photos profiles),
    gzip: false,
    cache_control_for_etags: "public, max-age=86400",
    headers: %{"x-content-type-options" => "nosniff"}
  )

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket("/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket)
    plug(Phoenix.LiveReloader)
    plug(Phoenix.CodeReloader)
    plug(Phoenix.Ecto.CheckRepoStatus, otp_app: :cherry)
  end

  plug(Plug.RequestId)
  plug(Plug.Telemetry, event_prefix: [:phoenix, :endpoint])
  plug(CherryWeb.Plugs.Cors)

  plug(Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    body_reader: {__MODULE__, :read_body_cache, []}
  )

  plug(Plug.MethodOverride)
  plug(Plug.Head)
  plug(Plug.Session, @session_options)
  plug(CherryWeb.Router)

  # Phoenix dispatches sockets before ordinary endpoint plugs. Wrap the generated
  # pipeline so the host boundary also rejects WebSocket upgrades on the staff host.
  @impl true
  def call(conn, opts) do
    conn = CherryWeb.Plugs.BackofficeHost.call(conn, [])
    if conn.halted, do: conn, else: super(conn, opts)
  end

  @doc """
  Custom body reader that caches the raw body for webhook signature verification.
  """
  def read_body_cache(conn, opts) do
    {:ok, body, conn} = Plug.Conn.read_body(conn, opts)

    # Identity documents (age verification) are never kept as a raw copy.
    if Enum.any?(
         [
           "/api/me/verification",
           "/backoffice",
           "/api/me/cases",
           "/api/auth/apple/browser",
           "/api/me/auth-methods"
         ],
         &String.starts_with?(conn.request_path, &1)
       ) do
      {:ok, body, conn}
    else
      {:ok, body, Plug.Conn.put_private(conn, :raw_body, body)}
    end
  end
end

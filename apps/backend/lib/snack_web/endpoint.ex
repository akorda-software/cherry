defmodule SnackWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :snack

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_snack_key",
    signing_salt: "ZJS2H4Vh",
    same_site: "Lax"
  ]

  socket("/socket", SnackWeb.UserSocket,
    websocket: [check_origin: false],
    longpoll: false
  )

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug(Plug.Static,
    at: "/",
    from: :snack,
    gzip: not code_reloading?,
    only: SnackWeb.static_paths(),
    raise_on_missing_only: code_reloading?
  )

  # Profile photos of the local storage adapter (Snack.Storage.Local), stored as
  # UPLOADS_DIR/<storage_key>. The directory is resolved per request (runtime
  # config). Only `profiles/` is exposed (never the `.tmp/` staging area), files
  # are immutable (unique keys, no overwrites) and directories are never listed.
  plug(Plug.Static,
    at: "/uploads",
    from: {Snack.Storage.Local, :uploads_dir, []},
    only: ~w(profiles),
    gzip: false,
    cache_control_for_etags: "public, max-age=31536000, immutable",
    headers: %{"x-content-type-options" => "nosniff"}
  )

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket("/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket)
    plug(Phoenix.LiveReloader)
    plug(Phoenix.CodeReloader)
    plug(Phoenix.Ecto.CheckRepoStatus, otp_app: :snack)
  end

  plug(Plug.RequestId)
  plug(Plug.Telemetry, event_prefix: [:phoenix, :endpoint])
  plug(SnackWeb.Plugs.Cors)

  plug(Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    body_reader: {__MODULE__, :read_body_cache, []}
  )

  plug(Plug.MethodOverride)
  plug(Plug.Head)
  plug(Plug.Session, @session_options)
  plug(SnackWeb.Router)

  @doc """
  Custom body reader that caches the raw body for webhook signature verification.
  """
  def read_body_cache(conn, opts) do
    {:ok, body, conn} = Plug.Conn.read_body(conn, opts)
    {:ok, body, Plug.Conn.put_private(conn, :raw_body, body)}
  end
end
